// Bundle src/ into dist/cordial.js (browsers: global `Cordial`; also CommonJS) and dist/cordial.cjs (same file, for require()).
// No dependencies: the modules are concatenated in dependency order with their import / export lines removed.
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const pkg = JSON.parse(readFileSync(join(root, "package.json"), "utf8"));
const order = ["constants.js", "equinox_table.js", "equinox.js", "time.js", "date.js"];

// the public names are the ones index.js re-exports
const index = readFileSync(join(root, "src", "index.js"), "utf8");
const names = [...index.matchAll(/export \{([^}]+)\} from/g)].flatMap((m) => m[1].split(",").map((s) => s.trim()).filter(Boolean));

const seen = new Map();
const body = order.map((file) => {
    const src = readFileSync(join(root, "src", file), "utf8");
    const code = src
        .split("\n")
        .filter((line) => !/^import\s/.test(line) && !/^export\s*\{.*\};?\s*$/.test(line))
        .map((line) => line.replace(/^export\s+(const|let|function|class)\s/, "$1 "))
        .join("\n");
    for (const m of code.matchAll(/^(?:const|let|function|class)\s+([A-Za-z_$][\w$]*)/gm)) {      // top-level names must be unique in one scope
        if (seen.has(m[1])) throw new Error(`name ${m[1]} is declared in both ${seen.get(m[1])} and ${file}`);
        seen.set(m[1], file);
    }
    return `// ---- ${file}\n${code.trim()}\n`;
}).join("\n");
for (const n of names) if (!seen.has(n)) throw new Error(`index.js exports ${n}, which no module declares`);

const out = `/*! lxcor-cordial ${pkg.version} | Apache-2.0 | https://github.com/lxcor/cordial-js | GENERATED by scripts/build.mjs from src/ */
(function (root, factory) {
    var api = factory();
    if (typeof module === "object" && module.exports) { module.exports = api; } else { root.Cordial = api; }
})(typeof self !== "undefined" ? self : this, function () {
"use strict";
${body}
return {${names.map((n) => `\n    ${n}: ${n}`).join(",")}
};
});
`;
mkdirSync(join(root, "dist"), { recursive: true });
writeFileSync(join(root, "dist", "cordial.js"), out);
writeFileSync(join(root, "dist", "cordial.cjs"), out);
console.log(`dist/cordial.js and dist/cordial.cjs written (${out.length} bytes, ${names.length} exports)`);
