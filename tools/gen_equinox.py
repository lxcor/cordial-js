"""Write src/equinox_table.js: the day of March of the March equinox (UTC date) for each year, from JPL DE440 with Skyfield.

    pip install skyfield
    python3 tools/gen_equinox.py [first_year] [last_year]          # default 2020 2100; downloads de440.bsp (114 MB) into tools/.ephemeris

The reference core (lxcor-cordial, Python) uses the same method; this table equals its dates for 2020-2052.
"""
import os, sys
from skyfield import almanac
from skyfield.api import Loader

first = int(sys.argv[1]) if len(sys.argv) > 1 else 2020
last = int(sys.argv[2]) if len(sys.argv) > 2 else 2100
here = os.path.dirname(os.path.abspath(__file__))
load = Loader(os.environ.get("EPHEMERIS_DIR", os.path.join(here, ".ephemeris")))
ts = load.timescale(); eph = load("de440.bsp")
f = almanac.seasons(eph)
days = {}
for y in range(first, last + 1):
    times, events = almanac.find_discrete(ts.utc(y, 3, 1), ts.utc(y, 4, 1), f)
    for t, e in zip(times, events):
        if e == 0:
            days[y] = t.utc_datetime().day
rows = ",\n".join("    %d: %d" % (y, days[y]) for y in sorted(days))
out = os.path.join(here, "..", "src", "equinox_table.js")
open(out, "w").write("""// GENERATED by tools/gen_equinox.py (JPL DE440, Skyfield): do not edit.
// Day of March (UTC calendar date) of the March equinox, %d-%d.
export const EQUINOX_FIRST_YEAR = %d;
export const EQUINOX_LAST_YEAR = %d;
export const EQUINOX_MARCH_DAY = {
%s
};
""" % (first, last, first, last, rows))
print("wrote", os.path.normpath(out), len(days), "years")
